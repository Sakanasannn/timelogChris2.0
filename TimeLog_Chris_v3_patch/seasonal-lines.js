window.CHRIS_SPECIAL_LINES.getAll = function () {
  const result = [];

  const add = (group) => {
    if (!group) return;

    if (Array.isArray(group)) {
      result.push(...group);
      return;
    }

    Object.values(group).forEach(value => {
      if (Array.isArray(value)) {
        result.push(...value);
      } else if (value && typeof value === "object") {
        Object.values(value).forEach(nested => {
          if (Array.isArray(nested)) {
            result.push(...nested);
          }
        });
      }
    });
  };

  add(this.weekdayMorning);
  add(this.specialNight);
  add(this.monthStart);
  add(this.monthEnd);
  add(this.holidays);

  Object.values(this.seasons).forEach(season => {
    add(season.morning);
    add(season.night);
  });

  return result;
};

window.CHRIS_SPECIAL_LINES.count = function () {
  return this.getAll().length;
};

